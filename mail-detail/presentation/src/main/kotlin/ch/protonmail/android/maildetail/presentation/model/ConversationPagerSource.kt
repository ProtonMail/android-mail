package ch.protonmail.android.maildetail.presentation.model

/**
 * What the detail screen swipes through.
 */
enum class ConversationPagerSource {

    /** The location the item was opened from. */
    Mailbox,

    /** The results of the active search. Swiping is off once that search is no longer active. */
    SearchResults,

    /** Only the opened item, such as a recent search result. */
    SingleItem
}
